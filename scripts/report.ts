// npx tsx scripts/report.ts data/baseline-v1.json docs/BASELINE-REPORT.md
// Re-scores stored runs with the current decision rule (no model calls) and
// writes a markdown report. Everything here is deterministic.
import { readFileSync, writeFileSync } from 'node:fs';
import { tallyDecision, DECISION_RULE } from '../api/_lib/committee';
import { mode, twoProportion, wilson } from '../api/_lib/stats';

type Letter = 'M' | 'N' | 'U';
interface Run {
  id: number;
  p: string;
  o: string;
  w: string | null;
  why: string;
  votes: Record<string, string>;
  contra: string[];
  verdicts: Record<string, string>;
  s: { checked: number; verified: number; downgraded: number; in: number; out: number; ms: number };
}
interface Data {
  experiment: string;
  snapshot: string;
  promptVersion: string;
  requirementOrder: string[];
  owners: Record<string, string>;
  runs: Run[];
}

const [, , inPath = 'data/baseline-v1.json', outPath = 'docs/BASELINE-REPORT.md'] = process.argv;
const data: Data = JSON.parse(readFileSync(inPath, 'utf8'));
const REQ = data.requirementOrder;
const REQ_TEXT: Record<string, string> = {
  D1: 'Predictable pricing (deal-breaker)',
  M1: 'EU data hosting',
  M2: 'Self-serve funnels/retention for PMs',
  M3: 'Works with Snowflake, no 2nd source of truth',
};
const ROLES = ['economic_buyer', 'technical_evaluator', 'champion', 'procurement', 'security_legal'];

/** "PostHog:NMMU* Mixpanel:UUMU pref=X" -> { PostHog: {D1:'N',...}, ... } */
function parse(s: string): { byVendor: Record<string, Record<string, Letter>>; pref: string; downgrades: number } {
  const byVendor: Record<string, Record<string, Letter>> = {};
  let pref = 'no_decision';
  let downgrades = 0;
  for (const tok of s.split(' ')) {
    if (tok.startsWith('pref=')) {
      pref = tok.slice(5);
      continue;
    }
    const [vendor, code] = tok.split(':');
    const letters = [...code].filter((c) => c !== '*') as Letter[];
    downgrades += [...code].filter((c) => c === '*').length;
    byVendor[vendor] = Object.fromEntries(REQ.map((r, i) => [r, letters[i]]));
  }
  return { byVendor, pref, downgrades };
}

const pct = (x: number) => `${Math.round(x * 100)}%`;
const ci = (k: number, n: number) => {
  const w = wilson(k, n);
  return `${pct(w.p)} (95% CI ${pct(w.lo)}–${pct(w.hi)})`;
};

const providers = [...new Set(data.runs.map((r) => r.p))];
const vendors = Object.keys(parse(data.runs[0].verdicts.economic_buyer).byVendor);

interface Scored extends Run {
  v2: ReturnType<typeof tallyDecision>;
  parsed: Record<string, ReturnType<typeof parse>>;
  blocked: Record<string, string[]>; // vendor -> requirement ids its owner did not see as met
}

const scored: Scored[] = data.runs.map((r) => {
  const parsed = Object.fromEntries(ROLES.map((role) => [role, parse(r.verdicts[role])]));
  const blocked: Record<string, string[]> = Object.fromEntries(vendors.map((v) => [v, []]));
  for (const req of REQ) {
    const owner = data.owners[req];
    for (const v of vendors) if (parsed[owner].byVendor[v][req] !== 'M') blocked[v].push(req);
  }
  const committeeEligible = vendors.filter((v) => blocked[v].length === 0);
  const eb = parsed.economic_buyer.byVendor;
  const ebEligible = new Set(vendors.filter((v) => REQ.every((q) => eb[v][q] !== 'N')));
  return { ...r, parsed, blocked, v2: tallyDecision(r.votes, committeeEligible, ebEligible) };
});

const out: string[] = [];
const line = (s = '') => out.push(s);

line(`# Baseline report — ${data.experiment}`);
line();
line(`Snapshot \`${data.snapshot}\` · prompt \`${data.promptVersion}\` · decision rule \`${DECISION_RULE}\` · runs: ${providers.map((p) => `${p} ${scored.filter((r) => r.p === p).length}`).join(', ')}`);
line();
line('Generated by `scripts/report.ts` from `data/' + inPath.split('/').pop() + '`. Re-run it to reproduce every number below.');
line();

// 1. Outcomes
line('## 1. Outcomes');
line();
line('| Model | Runs | No decision (rule v2) | Wins | Recorded under rule v1 |');
line('|---|---|---|---|---|');
for (const p of providers) {
  const rs = scored.filter((r) => r.p === p);
  const nd = rs.filter((r) => r.v2.result === 'no_decision').length;
  const wins = vendors.map((v) => [v, rs.filter((r) => r.v2.vendor === v).length] as const).filter(([, n]) => n);
  const v1wins = rs.filter((r) => r.o === 'win').map((r) => r.w);
  line(`| ${p} | ${rs.length} | ${ci(nd, rs.length)} | ${wins.length ? wins.map(([v, n]) => `${v} ${n}`).join(', ') : '0'} | ${v1wins.length ? `${v1wins.length} win (${v1wins.join(', ')})` : 'no wins'} |`);
}
line();
const why = new Map<string, number>();
for (const r of scored) if (r.v2.result === 'no_decision') why.set(r.v2.why, (why.get(r.v2.why) ?? 0) + 1);
line(`Why no decision (all runs): ${[...why.entries()].map(([k, n]) => `${k.replaceAll('_', ' ')} ${n}`).join(' · ')}.`);
line();
const v1only = scored.filter((r) => r.o === 'win' && r.v2.result !== 'win');
if (v1only.length)
  line(`Rule change: ${v1only.length} run(s) counted as a win under v1 are no decision under v2 (run ${v1only.map((r) => r.id).join(', ')}: the "winner" had ${Object.values(v1only[0].votes).filter((v) => v === v1only[0].w).length} of 5 votes).`);
line();

// 2. Blockers: the PMM readout
line('## 2. What blocks each vendor (owner verdicts)');
line();
line('Share of runs in which the requirement\'s owner did **not** find it met (N = shown as not met, U = unclear from the pages). This is the "missing proof" readout.');
line();
for (const p of providers) {
  const rs = scored.filter((r) => r.p === p);
  line(`**${p}** (n=${rs.length})`);
  line();
  line(`| Requirement (owner) | ${vendors.join(' | ')} |`);
  line(`|---|${vendors.map(() => '---').join('|')}|`);
  for (const req of REQ) {
    const owner = data.owners[req];
    const cells = vendors.map((v) => {
      const ls = rs.map((r) => r.parsed[owner].byVendor[v][req]);
      const notMet = ls.filter((l) => l !== 'M').length;
      const n = ls.filter((l) => l === 'N').length;
      const u = ls.filter((l) => l === 'U').length;
      return `${pct(notMet / rs.length)} (N${n}/U${u})`;
    });
    line(`| ${REQ_TEXT[req] ?? req} (${owner.replace('_', ' ')}) | ${cells.join(' | ')} |`);
  }
  line();
}

// 3. Cross-model agreement on owner verdicts
line('## 3. Do the two model families agree?');
line();
const cells: string[] = [];
let agree = 0;
let total = 0;
line(`| Requirement | ${vendors.join(' | ')} |`);
line(`|---|${vendors.map(() => '---').join('|')}|`);
for (const req of REQ) {
  const owner = data.owners[req];
  const row = vendors.map((v) => {
    const modes = providers.map((p) => mode(scored.filter((r) => r.p === p).map((r) => r.parsed[owner].byVendor[v][req])));
    total++;
    if (modes.every((m) => m === modes[0])) agree++;
    return providers.map((p, i) => `${p}:${modes[i]}`).join(' · ') + (modes.every((m) => m === modes[0]) ? ' ✓' : ' ✗');
  });
  cells.push(...row);
  line(`| ${REQ_TEXT[req] ?? req} | ${row.join(' | ')} |`);
}
line();
line(`Most common owner verdict matches on ${agree} of ${total} vendor × requirement cells (${pct(agree / total)}). Letters: M met, N not met, U unclear.`);
line();

// 4. Reliability
line('## 4. Reliability');
line();
line('| Model | Quotes verified | "Met" downgraded (no valid quote) | Agents contradicting own verdicts | Tokens / run | Median run time |');
line('|---|---|---|---|---|---|');
const rel: Record<string, { ver: number; chk: number; con: number; agents: number }> = {};
for (const p of providers) {
  const rs = scored.filter((r) => r.p === p);
  const chk = rs.reduce((a, r) => a + r.s.checked, 0);
  const ver = rs.reduce((a, r) => a + r.s.verified, 0);
  const down = rs.reduce((a, r) => a + r.s.downgraded, 0);
  const con = rs.reduce((a, r) => a + r.contra.length, 0);
  const agents = rs.length * 5;
  rel[p] = { ver, chk, con, agents };
  const tok = Math.round(rs.reduce((a, r) => a + r.s.in + r.s.out, 0) / rs.length);
  const ms = rs.map((r) => r.s.ms).sort((a, b) => a - b)[Math.floor(rs.length / 2)];
  line(`| ${p} | ${ci(ver, chk)} | ${down} | ${ci(con, agents)} | ${tok.toLocaleString('en')} | ${Math.round(ms / 1000)}s |`);
}
line();
if (providers.length === 2) {
  const [a, b] = providers;
  const q = twoProportion(rel[a].ver, rel[a].chk, rel[b].ver, rel[b].chk);
  const c = twoProportion(rel[a].con, rel[a].agents, rel[b].con, rel[b].agents);
  line(`Difference in quote verification (${b} − ${a}): ${pct(q.diff)}, p=${q.p.toFixed(4)}. Difference in contradiction rate: ${pct(c.diff)}, p=${c.p.toFixed(4)}.`);
  line();
}
line('Run time includes retries: Gemini\'s free tier returned 503 "high demand" for long stretches, so its times mostly measure waiting, not the model.');
line();

writeFileSync(outPath, out.join('\n') + '\n');
console.log(out.join('\n'));
